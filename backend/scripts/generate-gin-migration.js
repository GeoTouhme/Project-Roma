const GIN_KEYWORDS = ['Fords', 'Tanqueray Gin', 'The Botanist', 'Berry Bros', 'New Amsterdam', 'Hendrick', 'Monkey 47', 'Suntory', 'BOMBAY SAPPHIRE', 'MCQUEEN', 'Gin ', 'gin '];

let toMove = [];
let kept = [];
let unknown = [];

for (const line of lines) {
    const parts = line.split('|');
    if (parts.length < 4) continue;
    
    const name = parts[1];
    const id = parts[3].trim();
    
    // Check if it's explicitly GIN
    const isGin = GIN_KEYWORDS.some(k => name.toLowerCase().includes(k.toLowerCase()));
    if (isGin) {
        kept.push({ name, id });
        continue;
    }
    
    // Match targeting rules
    let matchedTarget = null;
    for (const rule of MAPPINGS) {
        if (rule.keyword.some(k => name.toLowerCase().includes(k.toLowerCase()))) {
            matchedTarget = rule.target;
            break;
        }
    }
    
    if (matchedTarget) {
        toMove.push(`  { productId: "${id}", targetCategory: "${matchedTarget}", name: "${name.replace(/"/g, '\\"')}" }`);
    } else {
        unknown.push(`  // UNKNOWN: { productId: "${id}", name: "${name.replace(/"/g, '\\"')}" }`);
    }
}

console.log(`To move: ${toMove.length}`);
console.log(`Kept as GIN: ${kept.length}`);
console.log(`Unknown: ${unknown.length}`);

if (unknown.length > 0) {
    console.log("\nUnknown products:");
    console.log(unknown.join('\n'));
}

